t() {
  if [ "$ML" = it ] && [ -n "${IT[$1]+x}" ]; then printf '%s' "${IT[$1]}";
  elif [ "$ML" = es ] && [ -n "${ES[$1]+x}" ]; then printf '%s' "${ES[$1]}";
  else printf '%s' "$1"; fi
}
tf() {
  local f; f=$(t "$1"); shift
  printf "$f" "$@"
}

